/**
 * GET /api/integration-map
 *
 * The application integration network: which apps exchange data with which,
 * through which APIs, hosted on which servers. Built from the explicit API
 * relationship columns added by scripts/backfill_api_relationships.js:
 *   FK_System Component[Applications].APP_ID              provider
 *   FK_System Components[Applications].APP_ID (Consumer)  consumer
 *   FK_System Components[Servers].SERVER_ID (Host)        host (derived)
 *
 * Response:
 *   apps:   every catalog app (from the Applications batches — canonical only
 *           holds 95 of the 100 because 5 acronyms are shared), with counts
 *   links:  one per provider→consumer app pair (cross-application APIs only),
 *           with the APIs on that link and the business flows they support
 *   hosts:  details for every server that hosts at least one API
 *   internalApiCount / unlinkedApiCount: what the links leave out, and why
 */
const express = require('express');
const mongoose = require('mongoose');
const CanonicalData = require('../models/CanonicalData');
const Diagram = require('../models/Diagram');
const { buildApiSequence, normalizeKey } = require('../services/apiSequence');

const router = express.Router();
const NEIGHBORHOOD = 'System Components';

const PROVIDER_KEYS = ['FK_System Component[Applications].APP_ID', 'FK_System Components[Applications].APP_ID'];
const CONSUMER_KEY = 'FK_System Components[Applications].APP_ID (Consumer)';
const HOST_KEY = 'FK_System Components[Servers].SERVER_ID (Host)';
const REQUEST_KEY = 'FK_System Components[Data Objects].OBJECT_ID (Request)';
const RESPONSE_KEY = 'FK_System Components[Data Objects].OBJECT_ID (Response)';
// Generic response envelope — not "data carried", so left out of link summaries.
const ACK_OBJECT_NAME = 'Transaction Acknowledgement';

const CACHE_TTL_MS = 5 * 60 * 1000;
let cache = null;

const text = (value) => String(value ?? '').trim();
const decodeEntities = (value) => text(value).replace(/&amp;/g, '&');

function getProviderAppId(values) {
  for (const key of PROVIDER_KEYS) {
    const value = text(values?.[key]);
    if (value) return value;
  }
  return '';
}

// "Customer Warranty Interest Qualification — Receive Customer at F&I Office API"
//   → flow "Customer Warranty Interest Qualification", task "Receive Customer at F&I Office"
function splitApiName(name) {
  const parts = decodeEntities(name).split(' — ');
  if (parts.length < 2) return { businessFlow: '', task: '' };
  return {
    businessFlow: parts[0].trim(),
    task: parts.slice(1).join(' — ').replace(/\s+API$/i, '').trim(),
  };
}

async function buildIntegrationMap() {
  const db = mongoose.connection.db;

  const appBatches = await db.collection('dataBatches')
    .find({ neighborhoodName: NEIGHBORHOOD, dataType: 'Applications' }, { projection: { rows: 1 } })
    .toArray();
  const appsById = new Map();
  for (const batch of appBatches) {
    for (const row of batch.rows || []) {
      const values = row.values || {};
      const id = text(values['APP_ID Qualifier']);
      if (!id || appsById.has(id)) continue;
      appsById.set(id, {
        id,
        acronym: text(values['APP_ACRONYM Component']) || id,
        name: decodeEntities(values['APP_NAME Qualifier']),
        domain: decodeEntities(values['BUSINESS_DOMAIN Aggregator']) || 'Unassigned',
        criticality: text(values['BUSINESS_CRITICALITY Aggregator'] || values['BUSINESS_CRITICALITY Qualifier']),
        providedApiCount: 0,
        consumedApiCount: 0,
        internalApiCount: 0,
      });
    }
  }

  // Data objects (generated by scripts/seed_api_data_objects.js — illustrative).
  const objectDocs = await CanonicalData.find(
    { neighborhoodName: NEIGHBORHOOD, componentType: 'Data Objects' },
    { values: 1 },
  ).lean();
  const dataObjects = {};
  for (const doc of objectDocs) {
    const values = doc.values || {};
    const id = text(values['OBJECT_ID Qualifier']);
    if (!id) continue;
    dataObjects[id] = {
      id,
      name: text(values['OBJECT_NAME Component']),
      category: text(values['Object Category Aggregate']),
      domain: text(values['Business Domain Aggregate']),
      sensitivity: text(values['Sensitivity Aggregate']),
      containsPii: text(values['Contains PII Aggregate']) === 'Yes',
      systemOfRecord: text(values['FK_System Components[Applications].APP_ID']),
      fields: Array.isArray(values.__fields) ? values.__fields : [],
    };
  }
  const ackId = Object.values(dataObjects).find((o) => o.name === ACK_OBJECT_NAME)?.id || '';

  const apiDocs = await CanonicalData.find(
    { neighborhoodName: NEIGHBORHOOD, componentType: 'APIs' },
    { values: 1 },
  ).lean();

  const linksByKey = new Map();
  const hostIds = new Set();
  // Every API (cross-app, internal and unlinked) by "flow|task", for the
  // per-flow sequence diagrams.
  const apiIndex = new Map();
  let internalApiCount = 0;
  let unlinkedApiCount = 0;

  for (const doc of apiDocs) {
    const values = doc.values || {};
    const provider = getProviderAppId(values);
    const consumer = text(values[CONSUMER_KEY]);
    const host = text(values[HOST_KEY]);
    if (host) hostIds.add(host);
    {
      const { businessFlow: flowName, task: taskName } = splitApiName(values['API Name Component']);
      if (flowName && taskName) {
        const indexKey = `${normalizeKey(flowName)}|${normalizeKey(taskName)}`;
        if (!apiIndex.has(indexKey)) apiIndex.set(indexKey, []);
        apiIndex.get(indexKey).push({
          id: text(values['API ID Qualifier']),
          name: decodeEntities(values['API Name Component']),
          method: text(values['HTTP Method Aggregate']),
          type: text(values['API Type Aggregate']),
          lifecycle: text(values['Lifecycle Status Aggregate']),
          endpoint: text(values['Endpoint Qualifier']),
          provider,
          consumer,
          host,
          requestObject: text(values[REQUEST_KEY]),
          responseObject: text(values[RESPONSE_KEY]),
        });
      }
    }

    if (!provider || !consumer || !appsById.has(provider) || !appsById.has(consumer)) {
      unlinkedApiCount += 1;
      continue;
    }
    if (provider === consumer) {
      internalApiCount += 1;
      appsById.get(provider).internalApiCount += 1;
      continue;
    }

    appsById.get(provider).providedApiCount += 1;
    appsById.get(consumer).consumedApiCount += 1;

    const key = `${provider}>${consumer}`;
    if (!linksByKey.has(key)) linksByKey.set(key, { source: provider, target: consumer, apis: [], businessFlows: new Set(), objectCounts: new Map() });
    const link = linksByKey.get(key);
    const { businessFlow, task } = splitApiName(values['API Name Component']);
    if (businessFlow) link.businessFlows.add(businessFlow);
    const requestObject = text(values[REQUEST_KEY]);
    const responseObject = text(values[RESPONSE_KEY]);
    for (const objectId of new Set([requestObject, responseObject])) {
      if (objectId && objectId !== ackId) link.objectCounts.set(objectId, (link.objectCounts.get(objectId) || 0) + 1);
    }
    link.apis.push({
      id: text(values['API ID Qualifier']),
      name: decodeEntities(values['API Name Component']),
      businessFlow,
      task,
      method: text(values['HTTP Method Aggregate']),
      type: text(values['API Type Aggregate']),
      lifecycle: text(values['Lifecycle Status Aggregate']),
      endpoint: text(values['Endpoint Qualifier']),
      host,
      requestObject,
      responseObject,
    });
  }

  const hostDocs = hostIds.size
    ? await CanonicalData.find(
      { neighborhoodName: NEIGHBORHOOD, componentType: 'Servers', 'values.SERVER_ID Qualifier': { $in: [...hostIds] } },
      { values: 1 },
    ).lean()
    : [];
  const hosts = {};
  for (const doc of hostDocs) {
    const values = doc.values || {};
    const id = text(values['SERVER_ID Qualifier']);
    if (!id || hosts[id]) continue;
    hosts[id] = {
      id,
      name: text(values['SERVER_NAME Component']) || id,
      role: text(values['SERVER_ROLE Aggregate']),
      city: text(values['LOCATION_CITY Aggregate']),
      datacenter: text(values['LOCATION_DATACENTER Qualifier']),
      environment: text(values['NETWORK_ZONE Aggregate']),
    };
  }

  const links = [...linksByKey.values()]
    .map((link) => ({
      source: link.source,
      target: link.target,
      count: link.apis.length,
      businessFlows: [...link.businessFlows].sort((a, b) => a.localeCompare(b)),
      // Data objects carried on this link (request or response), most frequent first.
      dataObjects: [...link.objectCounts.entries()]
        .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
        .map(([id, count]) => ({ id, count })),
      apis: link.apis.sort((a, b) => a.id.localeCompare(b.id)),
    }))
    .sort((a, b) => b.count - a.count);

  const data = {
    generatedAt: new Date().toISOString(),
    apps: [...appsById.values()].sort((a, b) => a.domain.localeCompare(b.domain) || a.acronym.localeCompare(b.acronym)),
    links,
    hosts,
    dataObjects,
    dataObjectNote: 'Data objects are generated (illustrative vocabulary assigned from task wording and HTTP method), not sourced from API specs.',
    hostAssignmentNote: 'Host servers are derived (one of the provider app\'s API Gateway servers), not sourced inventory.',
    internalApiCount,
    unlinkedApiCount,
  };
  return { data, apiIndex };
}

async function getIntegrationMapCached(fresh = false) {
  if (!fresh && cache && Date.now() - cache.at < CACHE_TTL_MS) return cache;
  const built = await buildIntegrationMap();
  cache = { at: Date.now(), ...built };
  return cache;
}

router.get('/', async (req, res) => {
  try {
    const fresh = String(req.query.fresh || '') === '1';
    const { data } = await getIntegrationMapCached(fresh);
    res.json(data);
  } catch (error) {
    console.error('[integration-map] failed:', error);
    res.status(500).json({ error: error?.message || 'Failed to build integration map' });
  }
});

/**
 * GET /api/integration-map/sequence/:diagramId
 *
 * The API calls a business flow makes, in process order: the diagram's tasks
 * ordered along its sequence flows, each joined to its API by the
 * "Flow — Task API" naming convention. Gateways become alt / par fragments.
 */
router.get('/sequence/:diagramId', async (req, res) => {
  try {
    if (!mongoose.isValidObjectId(req.params.diagramId)) return res.status(400).json({ error: 'Invalid diagram id' });
    const diagram = await Diagram.findById(req.params.diagramId, { name: 1, businessFlow: 1, domain: 1, subdomain: 1, xml: 1, tasks: 1 }).lean();
    if (!diagram) return res.status(404).json({ error: 'Diagram not found' });
    const { data, apiIndex } = await getIntegrationMapCached(false);
    res.json(buildApiSequence(diagram, { apiIndex, apps: data.apps, dataObjects: data.dataObjects, hosts: data.hosts }));
  } catch (error) {
    console.error('[integration-map] sequence failed:', error);
    res.status(500).json({ error: error?.message || 'Failed to build API sequence' });
  }
});

module.exports = router;
// Also used by scripts/export_mockprod_catalog.js.
module.exports.getIntegrationMapCached = getIntegrationMapCached;
